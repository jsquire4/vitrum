import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const FRAME_FIELDS = [
  ['width', 'u32'],
  ['height', 'u32'],
  ['frameIndex', 'u32'],
  ['frameSeed', 'u32'],
  ['triangleCount', 'u32'],
  ['maxBounces', 'u32'],
  ['bvhNodeCount', 'u32'],
  ['analyticCount', 'u32'],
  ['pointLightCount', 'u32'],
  ['spotLightCount', 'u32'],
  ['rectAreaLightCount', 'u32'],
  ['meshAreaLightCount', 'u32'],
  ['mneeMaxIterations', 'u32'],
  ['mneeMaxChainLength', 'u32'],
  ['hasEnvironmentMap', 'u32'],
  ['causticStrategy', 'u32'],
  ['environmentMapWidth', 'u32'],
  ['environmentMapHeight', 'u32'],
  ['triIntersectEpsilon', 'f32'],
  ['tlasNodeCount', 'u32'],
  ['cameraPos', 'vec4f'],
  ['lightDir', 'vec4f'],
  ['environmentTint', 'vec4f'],
  ['environmentSun', 'vec4f'],
  ['invViewProj', 'mat4x4f'],
  ['viewProj', 'mat4x4f'],
  ['prevViewProj', 'mat4x4f'],
];

const TYPE_SLOTS = { u32: 1, f32: 1, vec4f: 4, mat4x4f: 16 };

function generateFrame() {
  let slot = 0;
  const slotMap = [];
  for (const [name, type] of FRAME_FIELDS) {
    slotMap.push([name, slot]);
    slot += TYPE_SLOTS[type];
  }
  const fieldLines = FRAME_FIELDS.map(([n, t]) => `  '${n}: ${t}',`).join('\n');
  const slotLines = slotMap.map(([n, s]) => `  ${n}: ${s},`).join('\n');
  return `/** AUTO-GENERATED by tools/generate-wgsl-layouts.mjs */\nexport const FRAME_PARAMS_F32_SLOTS = ${slot};\n\nexport const FrameParamsSlot = {\n${slotLines}\n} as const;\n\nexport const FRAME_PARAMS_WGSL_FIELDS = [\n${fieldLines}\n] as const;\n`;
}

function generateRC() {
  return `/** AUTO-GENERATED by tools/generate-wgsl-layouts.mjs */\nexport const RC_PARAMS_BYTE_SIZE = 64;\n\nexport const RCParamsOffset = {\n  probeOriginWorld: 0,\n  rcWeight: 12,\n  roomSize: 16,\n  enabled: 28,\n  probeCount: 32,\n  raysPerProbe: 44,\n  rayGridSize: 48,\n} as const;\n`;
}

const frameOut = resolve(process.cwd(), 'packages/pt-webgpu/src/scene/frameParamsLayout.generated.ts');
const rcOut = resolve(process.cwd(), 'packages/walkaround-hybrid/src/rc/rcParamsLayout.generated.ts');
writeFileSync(frameOut, generateFrame());
writeFileSync(rcOut, generateRC());
console.log('generated', frameOut, rcOut);
