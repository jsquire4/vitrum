function reverseBits32(value: number): number {
  let x = value >>> 0;
  x = (((x & 0xaaaaaaaa) >>> 1) | ((x & 0x55555555) << 1)) >>> 0;
  x = (((x & 0xcccccccc) >>> 2) | ((x & 0x33333333) << 2)) >>> 0;
  x = (((x & 0xf0f0f0f0) >>> 4) | ((x & 0x0f0f0f0f) << 4)) >>> 0;
  x = (((x & 0xff00ff00) >>> 8) | ((x & 0x00ff00ff) << 8)) >>> 0;
  return ((x >>> 16) | (x << 16)) >>> 0;
}

function buildComponentDirections(): Uint16Array {
  const components = new Uint16Array(
    SOBOL_DIRECTION_DIMENSION_COUNT * SOBOL_DIRECTION_BITS,
  );
  const directions = new Uint32Array(SOBOL_DIRECTION_BITS);

  for (let dimension = 0; dimension < JOE_KUO_D6_ROWS.length; dimension += 1) {
    const row = JOE_KUO_D6_ROWS[dimension]!;
    const [sourceDimension, degree, polynomial, ...initial] = row;
    if (sourceDimension !== dimension + 2 || initial.length !== degree) {
      throw new Error(`invalid embedded Joe-Kuo direction row for dimension ${sourceDimension}`);
    }

    directions.fill(0);
    for (let bit = 0; bit < degree; bit += 1) {
      directions[bit] = ((initial[bit]! << (31 - bit)) >>> 0);
    }
    for (let bit = degree; bit < SOBOL_DIRECTION_BITS; bit += 1) {
      let value = (
        directions[bit - degree]! ^
        (directions[bit - degree]! >>> degree)
      ) >>> 0;
      for (let k = 1; k < degree; k += 1) {
        if (((polynomial >>> (degree - 1 - k)) & 1) !== 0) {
          value = (value ^ directions[bit - k]!) >>> 0;
        }
      }
      directions[bit] = value;
    }

    const offset = dimension * SOBOL_DIRECTION_BITS;
    for (let bit = 0; bit < SOBOL_DIRECTION_BITS; bit += 1) {
      // The runtime consumes the reversed low 16 bits. Storing that component
      // domain directly halves the WGSL table width without changing a sample.
      components[offset + bit] = reverseBits32(directions[bit]!) & 0xffff;
    }
  }
  return components;
}

const SOBOL_COMPONENT_DIRECTIONS = buildComponentDirections();

export function maskedSobolDirectionComponent(
  index: number,
  dimension: number,
): number {
  if (!Number.isInteger(dimension) || dimension < 0 ||
      dimension >= SOBOL_DIRECTION_DIMENSION_COUNT) {
    throw new RangeError(
      `dimension must be an integer in [0, ${SOBOL_DIRECTION_DIMENSION_COUNT - 1}]`,
    );
  }
  const sampleIndex = index >>> 0;
  const offset = dimension * SOBOL_DIRECTION_BITS;
  let out = 0;
  for (let bit = 0; bit < SOBOL_DIRECTION_BITS; bit += 1) {
    if (((sampleIndex >>> bit) & 1) !== 0) {
      out = (out ^ SOBOL_COMPONENT_DIRECTIONS[offset + bit]!) >>> 0;
    }
  }
  return out;
}

function buildPackedDirections(): Uint32Array {
  const packed = new Uint32Array(SOBOL_COMPONENT_DIRECTIONS.length / 2);
  for (let index = 0; index < packed.length; index += 1) {
    packed[index] = (
      SOBOL_COMPONENT_DIRECTIONS[index * 2]! |
      (SOBOL_COMPONENT_DIRECTIONS[index * 2 + 1]! << 16)
    ) >>> 0;
  }
  return packed;
}

function formatPackedDirectionsWgsl(): string {
  const packed = buildPackedDirections();
  const lines: string[] = [];
  for (let start = 0; start < packed.length; start += 8) {
    lines.push(
      '  ' +
      Array.from(packed.subarray(start, start + 8), (word) =>
        `0x${word.toString(16).padStart(8, '0')}u`
      ).join(', '),
    );
  }
  return lines.join(',\n');
}

/**
 * Binding-free WGSL table generated from the same direction rows as the CPU
 * oracle. Two reversed 16-bit direction components are packed into each u32.
 */
export const SOBOL_DIRECTION_NUMBERS_WGSL = /* wgsl */ `
const SOBOL_DIRECTION_BITS = ${SOBOL_DIRECTION_BITS}u;
const SOBOL_DIRECTION_DIMENSION_COUNT = ${SOBOL_DIRECTION_DIMENSION_COUNT}u;
// INLINE-BUDGET / driver note: this table is declared var<private> rather than
// const deliberately. It is read at a DYNAMIC index (dimension is a runtime
// value) from inside a fixed 16-iteration loop that Mesa unrolls, and a
// dynamically-indexed compile-time const array is lowered by scalarising it —
// which for 4096 entries, sixteen times over, made pipeline creation exhaust a
// 14GB budget and never converge. Declaring it as private storage with a
// constant initialiser keeps identical data and identical reads while letting
// the driver treat it as indexable memory. The array is never written, so every
// invocation observes the same values and results are unchanged.
var<private> SOBOL_DIRECTION_NUMBERS_PACKED: array<u32, ${
  SOBOL_DIRECTION_DIMENSION_COUNT * SOBOL_DIRECTION_BITS / 2
}> = array<u32, ${
  SOBOL_DIRECTION_DIMENSION_COUNT * SOBOL_DIRECTION_BITS / 2
}>(
${formatPackedDirectionsWgsl()}
);

fn sobolDirectionComponent(dimension: u32, bit: u32) -> u32 {
  let flatIndex = dimension * SOBOL_DIRECTION_BITS + bit;
  let packed = SOBOL_DIRECTION_NUMBERS_PACKED[flatIndex >> 1u];
  return (packed >> ((flatIndex & 1u) * 16u)) & 0xffffu;
}
`;
